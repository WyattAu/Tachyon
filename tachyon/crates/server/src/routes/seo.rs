/// Simple HTML escaping fallback
fn html_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(c),
        }
    }
    out
}

/// Create the SEO router with robots.txt, sitemap.xml, and SSR document page
pub fn create_seo_router() -> axum::Router<SeoState> {
    use axum::routing::get;

    axum::Router::new()
        .route("/robots.txt", get(robots_txt))
        .route("/sitemap.xml", get(sitemap_xml))
        .route("/docs/{document_id}", get(serve_document_page))
        .fallback(not_found)
}
