    #[test]
    fn test_split_statements_simple() {
        let sql = "BEGIN;\nCREATE TABLE foo (id INT);\nCOMMIT;";
        let stmts = split_statements(sql);
        assert_eq!(stmts.len(), 3);
        assert_eq!(stmts[0], "BEGIN");
        assert_eq!(stmts[1], "CREATE TABLE foo (id INT)");
        assert_eq!(stmts[2], "COMMIT");
    }

